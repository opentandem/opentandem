/** Whether a peer-to-peer binary is available for this machine (checks the platform only, no download). */
export function p2pSupportedHere() {
  if (process.env.OPENTANDEM_P2P === '0') return false
  return !!process.env.OPENTANDEM_P2P_NATIVE || !!p2pNativeAsset()
}

const p2pSha256File = async (file) => {
  const hash = p2pCrypto.createHash('sha256')
  for await (const chunk of p2pFs.createReadStream(file)) hash.update(chunk)
  return hash.digest('hex')
}

let p2pNativePromise = null
/** Get the native exports of node-datachannel (PeerConnection etc.). A failure can be retried. */
export function p2pEnsureNative(log = () => {}) {
  if (!p2pNativePromise) {
    p2pNativePromise = p2pLoadNative(log).catch(error => { p2pNativePromise = null; throw error })
  }
  return p2pNativePromise
}

async function p2pLoadNative(log) {
  const configured = process.env.OPENTANDEM_P2P_NATIVE?.trim()
  let file = configured || null
  if (!file) {
    const asset = p2pNativeAsset()
    if (!asset) throw new Error(`p2p unsupported platform: ${process.platform}/${process.arch}`)
    const dir = p2pPath.join(p2pOs.homedir(), '.local', 'share', 'opentandem', 'native', `node-datachannel-${P2P_NATIVE_VERSION}-${asset.target}`)
    const managed = p2pPath.join(dir, 'node_datachannel.node')
    if (await p2pSha256File(managed).catch(() => '') !== asset.sha256) {
      p2pFs.mkdirSync(dir, { recursive: true, mode: 0o700 })
      const stage = p2pFs.mkdtempSync(p2pPath.join(dir, '.install-'))
      const part = p2pPath.join(stage, asset.filename)
      try {
        for (let attempt = 0; attempt < 2; attempt++) {
          const controller = new AbortController()
          const total = setTimeout(() => controller.abort(), 180_000)
          let idle = setTimeout(() => controller.abort(), 15_000)
          let out
          try {
            const res = await fetch(asset.url, { signal: controller.signal, redirect: 'error' })
            if (!res.ok || !res.body) throw new Error(`CDN HTTP ${res.status}`)
            out = await p2pFs.promises.open(part, 'w', 0o600)
            let size = 0
            for await (const chunk of res.body) {
              clearTimeout(idle); idle = setTimeout(() => controller.abort(), 15_000)
              size += chunk.length
              if (size > asset.size) throw new Error('CDN file exceeds pinned size')
              await out.writeFile(chunk)
            }
            await out.close(); out = null
            if (size !== asset.size || await p2pSha256File(part) !== asset.sha256) throw new Error('CDN file checksum mismatch')
            break
          } catch (error) {
            if (attempt === 1) throw error
          } finally {
            clearTimeout(total); clearTimeout(idle); controller.abort(); await out?.close()
          }
        }
        p2pFs.chmodSync(part, 0o700)
        if (await p2pSha256File(managed).catch(() => '') !== asset.sha256) p2pFs.renameSync(part, managed)
      } finally {
        p2pFs.rmSync(stage, { recursive: true, force: true })
      }
      log(`native ready: ${asset.target}`)
    }
    file = managed
  }
  // The native module exports the PeerConnection / DataChannel classes directly, so no JS wrapper layer is needed.
  const mod = { exports: {} }
  process.dlopen(mod, file)
  if (!mod.exports.PeerConnection) throw new Error('native module has no PeerConnection')
  return mod.exports
}

// ---- Path rules -----------------------------------------------------------------
const p2pInsideDir = (child, parent) => {
  const rel = p2pPath.relative(parent, child)
  return rel === '' || (!!rel && !rel.startsWith('..') && !p2pPath.isAbsolute(rel))
}
// 0.87.0: every disk access on this path is async. P2P serves page images while
// tasks run; a synchronous lstat on a slow or hung disk froze heartbeats and every
// other request on the Runner's main thread.
const p2pRealpathOr = async (p) => { try { return await p2pFs.promises.realpath(p) } catch { return null } }

const p2pHtmlResource = /\.(?:html?|pdf|css|png|jpe?g|gif|webp|avif|svg|ico|woff2?|ttf|otf|eot|mp4|webm|ogg|mp3|wav)$/i

async function p2pHasSymlink(file, workdir) {
  let current = p2pPath.resolve(file)
  for (;;) {
    if ((await p2pFs.promises.lstat(current)).isSymbolicLink()) {
      // The configured workdir is a trusted boundary, including its ancestors.
      // macOS also exposes system /tmp, /var and /etc through /private aliases.
      // Neither exception permits links beneath the workdir or artifact directory.
      const workdirAncestor = workdir && p2pInsideDir(p2pPath.resolve(workdir), current) && current !== p2pPath.resolve(file)
      const systemAlias = process.platform === 'darwin' && ['/tmp', '/var', '/etc'].includes(current) &&
        current !== p2pPath.resolve(file) && await p2pFs.promises.realpath(current) === `/private${current}`
      if (!workdirAncestor && !systemAlias) return true
    }
    const parent = p2pPath.dirname(current)
    if (parent === current) return false
    current = parent
  }
}

// Scan large documents in fixed-size windows: inline data images must not
// prevent references near the end from being discovered. Local URLs are capped
// by the protocol's 4096-character path limit; unusually huge attributes are
// ignored without retaining their text in memory.
async function* p2pDocumentRefs(file) {
  const Decoder = process.getBuiltinModule('node:string_decoder').StringDecoder
  const decoder = new Decoder('utf8')
  const chunk = Buffer.alloc(64 * 1024)
  const handle = await p2pFs.promises.open(file, 'r')
  let text = ''
  try {
    for (;;) {
      const length = (await handle.read(chunk, 0, chunk.length, null)).bytesRead
      text += length ? decoder.write(chunk.subarray(0, length)) : decoder.end()
      const cutoff = length ? Math.max(0, text.length - 64 * 1024) : text.length
      const refs = /(?:\b(srcset|src|href|poster)\s*=\s*(?:"([^"]{1,32768})"|'([^']{1,32768})'|([^\s>"']{1,4096})(?=[\s>])))|(?:url\(\s*["']?([^"')]{1,4096})["']?\s*\))|(?:@import\s+["']([^"']{1,4096})["'])/gi
      for (const match of text.matchAll(refs)) {
        if (match.index >= cutoff) break
        const value = (match[2] || match[3] || match[4] || match[5] || match[6] || '').trim()
        if (match[1]?.toLowerCase() !== 'srcset') { yield value; continue }
        // URL tokens include embedded commas (data URLs); descriptors end at a
        // comma. Do not turn the payload of a data URL into a local filename.
        let rest = value
        while (rest) {
          rest = rest.replace(/^[\s,]+/, '')
          const token = /^[^\s]+/.exec(rest)?.[0]
          if (!token) break
          yield token.replace(/,+$/, '')
          rest = rest.slice(token.length)
          if (!token.endsWith(',')) { const comma = rest.indexOf(','); rest = comma < 0 ? '' : rest.slice(comma + 1) }
        }
      }
      if (!length) break
      text = text.slice(cutoff)
    }
  } finally { await handle.close().catch(() => {}) }
}

/**
 * Upload file name: strip directories and control characters and limit the length. The extension is kept
 * so the Runner's image channel can recognize the file by its suffix.
 */
export function p2pSafeUploadName(name) {
  const base = String(name || '').replace(/\\/g, '/').split('/').pop() || ''
  const cleaned = base.replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '').replace(/^\.+/, '').trim()
  const ext = p2pPath.extname(cleaned).slice(0, 12)
  const stem = p2pPath.basename(cleaned, p2pPath.extname(cleaned)).slice(0, 100)
  return (stem || 'file') + ext
}

// ---- Main body ------------------------------------------------------------------
/**
 * @param {object} deps
 *  machineId, daemonVersion
 * verifyTicket(token) -> ticket payload or null (verified offline with the public key sent in the
 *    heartbeat)
 * artifactRoots(workdir) -> array of directories; resolveArtifactAbs(ref, roots) -> absolute path or
 *    null (both may return a Promise)
 *  isSensitive(absPath) -> boolean; mimeFor(absPath) -> string
 * taskArtifacts(taskId) -> Promise<string[]>: artifact paths the server has recorded for the task
 *    (attachments + artifact_offers)
 *  log(msg)
 */
export function createP2PRunner(deps) {
  const log = deps.log || (() => {})
  const sensitive = file => deps.isSensitive(file.replace(/\\/g, '/'))
  const peers = new Map() // session_id → { pc, dc, openedAt, lastActive }
  // When a file request or chunk last moved on any channel. Keepalive pings refresh a peer's
  // lastActive (so an idle-but-open page keeps its channel) but must not count here: an open
  // page pings every 15s, and counting that postponed self-update forever.
  let lastTransferAt = 0
  const markTransfer = () => { lastTransferAt = Date.now() }
  // Files outside the working directory are only accepted if the server has an artifact record for them
  // (stored by
  // task id + path). We do not keep a second copy in Runner memory: the old in-memory list was cleared on every
  // restart, so after one auto-update all images outside the working directory in old sessions were rejected (2026-10-16).
  const serverAllow = new Map() // task_id -> { at, files: Set<real path>, htmlFiles: real path[], pending }
  let enabled = false
  let fileEnabled = false
  let maxPeers = 4
  let janitor = null
  let webPreview = null

  const startJanitor = () => {
    if (janitor) return
    janitor = setInterval(() => {
      const now = Date.now()
      for (const [sid, peer] of peers) {
        const stale = peer.state !== 'open' ? now - peer.openedAt > 40_000 : now - peer.lastActive > 10 * 60_000
        if (stale) closePeer(sid, 'idle')
        else for (const up of peer.uploads.values()) {
          if (now - up.lastActive > 60_000 || up.ticket.exp <= now) discardUpload(peer, up)
        }
      }
      if (!peers.size) { clearInterval(janitor); janitor = null }
    }, 15_000)
    janitor.unref?.()
  }

  function closePeer(sid, why) {
    const peer = peers.get(sid)
    if (!peer) return
    peers.delete(sid)
    peer.cleanup?.()
    log(`peer ${sid} closed: ${why}`)
    try { peer.dc?.close() } catch { /* already closed */ }
    try { peer.pc?.close() } catch { /* already closed */ }
    for (const u of peer.uploads.values()) discardUpload(peer, u)
  }

  function discardUpload(peer, up) {
    up.failed = true
    up.queued = []
    if (peer.uploads.get(up.id) === up) peer.uploads.delete(up.id)
    // The file is not created yet: the file-creation step deletes its own leftover fragment when it sees failed.
    if (!up.stream) return
    const cleanup = () => p2pFs.rm(up.tmp, { force: true }, () => { /* a fragment that cannot be deleted does not affect later uploads */ })
    if (up.stream.closed) cleanup()
    else { up.stream.once('close', cleanup); up.stream.destroy() }
  }

  /**
   * Artifacts the server has recorded for the task, cached per task. A hit is reused for 60 seconds;
   * when nothing is found, ask again at most once every 2 seconds.
   */
  async function serverAllowance(ticket, refresh) {
    const now = Date.now()
    const cached = serverAllow.get(ticket.task)
    if (cached && (now - cached.at < (refresh ? 2_000 : 60_000))) return cached.pending || cached
    const entry = { at: now, files: new Set(), htmlFiles: [], pending: null }
    entry.pending = (async () => {
      let paths = []
      try { paths = await deps.taskArtifacts(ticket.task) } catch (e) { log(`task artifacts lookup failed: ${e instanceof Error ? e.message : e}`) }
      for (const abs of Array.isArray(paths) ? paths : []) {
        if (typeof abs !== 'string' || !abs) continue
        const real = await p2pRealpathOr(abs)
        if (!real || sensitive(abs) || sensitive(real)) continue
        try { if (await p2pHasSymlink(abs, ticket.wd)) continue } catch { continue }
        entry.files.add(real)
        if (/\.html?$/i.test(real)) entry.htmlFiles.push(real)
      }
      entry.pending = null
      return entry
    })()
    serverAllow.delete(ticket.task)
    serverAllow.set(ticket.task, entry)
    while (serverAllow.size > 200) serverAllow.delete(serverAllow.keys().next().value)
    return entry.pending
  }

  /**
   * Outside the working directory only server-recorded artifacts are allowed. The parent directory used for
   * resolution (the repository root) grants no read access.
   */
  async function readAllowance(ticket, refresh = false) {
    const server = await serverAllowance(ticket, refresh)
    return { files: server.files, htmlFiles: server.htmlFiles }
  }

  // Follow only references actually present in reported HTML/CSS, never grant
  // the whole containing directory. Bound parsing work and stay under each
  // reported document's directory, including for nested HTML and CSS imports.
  async function htmlResources(allow, ticket) {
    const resources = new Set()
    const queue = allow.htmlFiles.map(file => ({ file, root: p2pPath.dirname(file) }))
    const visited = new Set()
    while (queue.length && visited.size < 200 && resources.size < 200) {
      const { file, root } = queue.shift()
      const key = `${root}\0${file}`
      if (visited.has(key)) continue
      visited.add(key)
      try {
        for await (const value of p2pDocumentRefs(file)) {
          if (resources.size >= 200) break
          const raw = value.trim().replace(/&amp;/g, '&')
          const abs = artifactLocalReference(raw, file)
          if (!abs) continue
          if (!p2pHtmlResource.test(abs) || !p2pInsideDir(abs, root) || sensitive(abs)) continue
          const real = await p2pRealpathOr(abs)
          if (!real || !p2pInsideDir(real, root) || sensitive(real)) continue
          try { if (await p2pHasSymlink(abs, ticket.wd) || !(await p2pFs.promises.stat(real)).isFile()) continue } catch { continue }
          resources.add(real)
          if (/\.(?:html?|css)$/i.test(real)) queue.push({ file: real, root })
        }
      } catch { /* The reported file may have disappeared during scanning. */ }
    }
    return resources
  }

  /**
   * Resolve the path given by the browser into a real file that is allowed to be read; otherwise return { code }.
   */
  async function resolveReadable(ticket, ref) {
    if (typeof ref !== 'string' || !ref || ref.includes('\0') || ref.length > 4096) return { code: P2P_ERR.BAD_REQUEST }
    const roots = ticket.wd ? await deps.artifactRoots(ticket.wd) : []
    const abs = await deps.resolveArtifactAbs(ref, roots)
    if (!abs) return { code: P2P_ERR.NOT_FOUND }
    const real = await p2pRealpathOr(abs)
    if (!real) return { code: P2P_ERR.NOT_FOUND }
    if (sensitive(abs) || sensitive(real)) return { code: P2P_ERR.FORBIDDEN }
    try { if (await p2pHasSymlink(abs, ticket.wd)) return { code: P2P_ERR.FORBIDDEN } } catch { return { code: P2P_ERR.NOT_FOUND } }
    const workdir = ticket.wd ? await p2pRealpathOr(ticket.wd) : null
    if (!(workdir && p2pInsideDir(real, workdir))) {
      const permitted = async allow => allow.files.has(real) || (await htmlResources(allow, ticket)).has(real)
      if (!await permitted(await readAllowance(ticket)) && !await permitted(await readAllowance(ticket, true))) return { code: P2P_ERR.FORBIDDEN }
    }
    let st
    try { st = await p2pFs.promises.stat(real) } catch { return { code: P2P_ERR.NOT_FOUND } }
    if (!st.isFile()) return { code: P2P_ERR.NOT_FOUND }
    return { real, st }
  }

  /** Send a binary frame; wait while the send buffer is above the high-water mark. */
  function makeSender(dc) {
    const waiters = []
    dc.setBufferedAmountLowThreshold(P2P_LOW_WATER)
    dc.onBufferedAmountLow(() => { while (waiters.length) waiters.shift()() })
    return {
      json: (obj) => { try { dc.sendMessage(JSON.stringify(obj)) } catch { /* the peer has gone */ } },
      async chunk(id, bytes, active = () => true) {
        while (active() && dc.isOpen() && dc.bufferedAmount() > P2P_HIGH_WATER) {
          await new Promise(resolve => { waiters.push(resolve); setTimeout(resolve, 1000) })
        }
        if (active() && dc.isOpen()) { dc.sendMessageBinary(p2pPackChunk(id, bytes)); markTransfer() }
      },
    }
  }

  function attachChannel(sid, peer, dc) {
    const send = makeSender(dc)
    peer.dc = dc
    // One channel can serve several tasks on the same machine: each task has its own ticket (the browser
    // sends one hello per ticket).
    // A request carries task to pick the ticket; with only one ticket (an old page that sends no task)
    // that ticket is used.
    const tickets = new Map()
    let inflight = 0
    const cancelled = new Set()
    const activeGets = new Set()
    const previews = new Map()
    webPreview ||= createRunnerWebPreview({ verifyTicket: deps.verifyTicket, machineId: deps.machineId })
    const dropPreview = (id, abort = true) => {
      const pending = previews.get(id)
      if (!pending) return
      clearTimeout(pending.timer)
      if (abort) pending.controller.abort()
      pending.collector?.clear()
      previews.delete(id)
    }
    peer.cleanup = () => {
      clearTimeout(helloTimer)
      for (const id of previews.keys()) dropPreview(id)
    }
    const helloTimer = setTimeout(() => { if (!tickets.size) closePeer(sid, 'no hello') }, 10_000)
    helloTimer.unref?.()
    const fail = (id, code) => send.json({ t: 'err', ...(id !== undefined ? { id } : {}), code })
    const ticketFor = (msg) => {
      const t = typeof msg?.task === 'string' ? tickets.get(msg.task) : (tickets.size === 1 ? tickets.values().next().value : undefined)
      return t && t.exp > Date.now() ? t : null
    }

    dc.onOpen(() => { peer.state = 'open'; peer.lastActive = Date.now() })
    dc.onClosed(() => closePeer(sid, 'channel closed'))

    async function doGet(msg, ticket) {
      const { id } = msg
      if (!fileEnabled || !ticket.down) return fail(id, P2P_ERR.FORBIDDEN)
      const r = await resolveReadable(ticket, msg.path)
      if (!r.real) return fail(id, r.code)
      if (r.st.size > P2P_MAX_DOWNLOAD_BYTES) return fail(id, P2P_ERR.TOO_LARGE)
      let preview
      try { preview = await readArtifactPreview(r.real, r.st, msg.view) } catch { return fail(id, P2P_ERR.NOT_FOUND) }
      preview ||= await displayImage(r.real, r.st, msg.view)
      const size = preview ? preview.bytes.length : r.st.size
      const offset = Math.max(0, Math.min(Number(msg.offset) || 0, size))
      const length = Math.max(0, Math.min(msg.length === undefined ? size - offset : Number(msg.length) || 0, size - offset))
      send.json({ t: 'meta', id, size, mime: preview?.mime || deps.mimeFor(r.real), offset, length, mtime_ms: Math.round(r.st.mtimeMs) })
      let fd
      try {
        if (!preview) fd = await p2pFs.promises.open(r.real, 'r')
        const buf = Buffer.allocUnsafe(P2P_CHUNK_SIZE)
        let pos = offset
        const end = offset + length
        while (pos < end) {
          if (!fileEnabled) return fail(id, P2P_ERR.FORBIDDEN)
          if (cancelled.has(id) || !dc.isOpen()) return
          const want = Math.min(P2P_CHUNK_SIZE, end - pos)
          const bytesRead = preview ? preview.bytes.copy(buf, 0, pos, pos + want) : (await fd.read(buf, 0, want, pos)).bytesRead
          if (!bytesRead) break
          await send.chunk(id, buf.subarray(0, bytesRead), () => fileEnabled && !cancelled.has(id))
          pos += bytesRead
          peer.lastActive = Date.now()
        }
        if (!fileEnabled) return fail(id, P2P_ERR.FORBIDDEN)
        if (!cancelled.has(id)) send.json({ t: 'end', id })
      } catch { fail(id, P2P_ERR.IO) } finally { await fd?.close().catch(() => {}) }
    }

    function doPut(msg, ticket) {
      const { id } = msg
      if (!fileEnabled || !ticket.up || !ticket.wd) return fail(id, P2P_ERR.FORBIDDEN)
      const size = Number(msg.size)
      if (!Number.isSafeInteger(size) || size < 0) return fail(id, P2P_ERR.BAD_REQUEST)
      if (size > P2P_MAX_FILE_BYTES) return fail(id, P2P_ERR.TOO_LARGE)
      const sha256 = typeof msg.sha256 === 'string' && /^[0-9a-f]{64}$/.test(msg.sha256) ? msg.sha256 : ''
      if (peer.uploads.has(id)) return fail(id, P2P_ERR.BAD_REQUEST)
      // One subdirectory per task: .sophon/uploads/<task id>/.
      const task = String(ticket.task || '')
      if (!/^[\w-]{1,64}$/.test(task)) return fail(id, P2P_ERR.FORBIDDEN)
      // After sending put, the browser starts sending content without waiting for a reply: register first, and queue
      // chunks that arrive before the file is created (limit P2P_PUT_QUEUE_MAX).
      const up = { id, ticket, size, got: 0, sha256, hash: p2pCrypto.createHash('sha256'), final: '', tmp: '', stream: null, queued: [], queuedBytes: 0, mime: String(msg.mime || '').slice(0, 128), failed: false, lastActive: Date.now(), ending: false }
      peer.uploads.set(id, up)
      up.ready = (async () => {
        const wd = await p2pFs.promises.realpath(ticket.wd)
        const base = p2pPath.join(wd, '.sophon', 'uploads')
        const dir = p2pPath.join(base, task)
        // Check each managed component before mkdir can follow a pre-existing link.
        for (const part of [p2pPath.dirname(base), base, dir]) {
          try {
            const st = await p2pFs.promises.lstat(part)
            if (!st.isDirectory() || st.isSymbolicLink()) throw Object.assign(new Error('forbidden'), { p2pCode: P2P_ERR.FORBIDDEN })
          } catch (error) { if (error.code !== 'ENOENT') throw error; await p2pFs.promises.mkdir(part, { mode: 0o700 }) }
        }
        up.final = p2pPath.join(dir, `${p2pCrypto.randomBytes(12).toString('hex')}-${p2pSafeUploadName(msg.name)}`)
        up.tmp = `${up.final}.part`
        const fd = await new Promise((resolve, reject) => p2pFs.open(up.tmp, 'wx', 0o600, (error, fd) => error ? reject(error) : resolve(fd)))
        const stream = p2pFs.createWriteStream(up.tmp, { fd, autoClose: true })
        up.stream = stream
        stream.on('error', () => { discardUpload(peer, up); fail(id, P2P_ERR.IO) })
        if (up.failed) { discardUpload(peer, up); return false }
        for (const bytes of up.queued) stream.write(bytes)
        up.queued = []
        up.queuedBytes = 0
        return true
      })().catch(error => {
        if (!up.failed) { discardUpload(peer, up); fail(id, error?.p2pCode || P2P_ERR.IO) }
        return false
      })
      // Returned to the message handler: it does not block other messages (the data channel does not wait for the handler),
      // and tests and logs can still wait for the result of file creation.
      return up.ready
    }

    async function endPut(msg) {
      const up = peer.uploads.get(msg.id)
      if (!up || up.ending) return fail(msg.id, P2P_ERR.BAD_REQUEST)
      if (!fileEnabled) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.FORBIDDEN) }
      if (up.ticket.exp <= Date.now()) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.AUTH) }
      up.ending = true
      if (!await up.ready) return
      await new Promise(resolve => { up.stream.once('close', resolve); up.stream.end() })
      if (!fileEnabled) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.FORBIDDEN) }
      if (up.failed || !dc.isOpen()) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.IO) }
      if (up.got !== up.size) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.BAD_REQUEST) }
      if (up.sha256 && up.hash.digest('hex') !== up.sha256) { discardUpload(peer, up); return fail(msg.id, P2P_ERR.HASH_MISMATCH) }
      try { await p2pFs.promises.rename(up.tmp, up.final) } catch { discardUpload(peer, up); return fail(msg.id, P2P_ERR.IO) }
      peer.uploads.delete(msg.id)
      send.json({ t: 'put_ok', id: msg.id, path: up.final, size: up.got })
    }

    function startPreview(msg, ticket) {
      if (ticket.preview !== true) return fail(msg.id, P2P_ERR.FORBIDDEN)
      if (previews.size >= P2P_MAX_INFLIGHT) return fail(msg.id, P2P_ERR.BUSY)
      try {
        const collector = p2pPreviewCollector(msg.length)
        const timer = setTimeout(() => { dropPreview(msg.id); fail(msg.id, 'timeout') }, 120_000)
        timer.unref?.()
        previews.set(msg.id, { task: ticket.task, collector, controller: new AbortController(), timer, running: false })
      } catch (error) { fail(msg.id, error.code || P2P_ERR.BAD_REQUEST) }
    }

    const p2pGzip = (bytes) => new Promise((resolve, reject) => {
      const zlib = process.getBuiltinModule('node:zlib')
      zlib.gzip(bytes, { level: 6 }, (error, out) => error ? reject(error) : resolve(out))
    })

    /**
     * Replace a large PNG/JPEG in a preview with a display version (long edge 2048, JPEG 80); the original is untouched.
     * If it cannot be compressed, return it as is.
     */
    async function shrinkPreviewImage(value) {
      try {
        if (!deps.shrinkImage || value.status !== 200 || typeof value.body !== 'string' || !Array.isArray(value.headers)) return
        if (value.headers.some(([name]) => /^content-range$/i.test(name))) return
        const typeAt = value.headers.findIndex(([name]) => /^content-type$/i.test(name))
        const mime = typeAt >= 0 ? String(value.headers[typeAt][1]).split(';')[0].trim().toLowerCase() : ''
        if (mime !== 'image/png' && mime !== 'image/jpeg') return
        if (value.body.length * 0.75 < P2P_DISPLAY_IMAGE_MIN) return
        const original = Buffer.from(value.body, 'base64')
        const shrunk = await deps.shrinkImage(original, mime)
        if (!shrunk || shrunk.bytes.length >= original.length * 0.9) return
        value.body = shrunk.bytes.toString('base64')
        value.headers[typeAt] = [value.headers[typeAt][0], shrunk.mime]
        value.raw = original.length
      } catch { /* if compression is not possible, send the original */ }
    }

    /**
     * Display version: only used for image previews in the conversation (view=display). Non-images, files that are too
     * small, and files that cannot be compressed return null, and the caller reads the original file.
     */
    async function displayImage(real, st, view) {
      if (view !== P2P_DISPLAY_VIEW || !deps.shrinkImage || st.size < P2P_DISPLAY_IMAGE_MIN) return null
      const mime = /\.png$/i.test(real) ? 'image/png' : /\.jpe?g$/i.test(real) ? 'image/jpeg' : ''
      if (!mime) return null
      try {
        const original = await p2pFs.promises.readFile(real)
        const shrunk = await deps.shrinkImage(original, mime)
        return shrunk && shrunk.bytes.length < original.length * 0.9 ? shrunk : null
      } catch { return null }
    }

    async function endPreview(msg) {
      const pending = previews.get(msg.id)
      if (!pending || pending.running) return fail(msg.id, P2P_ERR.BAD_REQUEST)
      pending.running = true
      try {
        const ticket = ticketFor({ task: pending.task })
        if (!ticket) return fail(msg.id, P2P_ERR.AUTH)
        if (ticket.preview !== true) return fail(msg.id, P2P_ERR.FORBIDDEN)
        const body = pending.collector.finish()
        pending.collector.clear()
        if (!P2P_PREVIEW_OPS.includes(body.op) || !body.args || typeof body.args !== 'object' || Array.isArray(body.args)) return fail(msg.id, P2P_ERR.BAD_REQUEST)
        const value = await webPreview.request(pending.task, body.op, body.args, pending.controller.signal)
        if (!previews.has(msg.id) || !dc.isOpen()) return
        if (body.z === 1 && body.op === 'http') await shrinkPreviewImage(value)
        if (!previews.has(msg.id) || !dc.isOpen()) return
        let bytes = p2pPreviewEncode(value)
        let enc
        // Compress only if the browser declares it can decode gzip (z:1). Older Runners do not know this field
        // and send the original.
        if (body.z === 1 && bytes.byteLength >= P2P_PREVIEW_GZIP_MIN) {
          const zipped = await p2pGzip(bytes)
          if (zipped.byteLength < bytes.byteLength) { bytes = zipped; enc = 'gzip' }
        }
        if (!previews.has(msg.id) || !dc.isOpen()) return
        send.json({ t: 'preview_meta', id: msg.id, length: bytes.byteLength, ...(enc ? { enc } : {}) })
        for (let at = 0; at < bytes.byteLength; at += P2P_CHUNK_SIZE) {
          if (!previews.has(msg.id) || !dc.isOpen()) return
          await send.chunk(msg.id, bytes.subarray(at, at + P2P_CHUNK_SIZE), () => previews.has(msg.id))
        }
        if (previews.has(msg.id)) send.json({ t: 'end', id: msg.id })
      } catch (error) {
        if (previews.has(msg.id)) fail(msg.id, error.code || P2P_ERR.IO)
      } finally { dropPreview(msg.id, false) }
    }

    dc.onMessage(async (data) => {
      peer.lastActive = Date.now()
      try {
        if (typeof data !== 'string') { // binary frame: upload content
          markTransfer()
          const frame = p2pUnpackChunk(data)
          const preview = frame && previews.get(frame.id)
          if (preview) {
            try {
              if (preview.running) throw Object.assign(new Error('bad_request'), { code: P2P_ERR.BAD_REQUEST })
              const ticket = ticketFor({ task: preview.task })
              if (!ticket || ticket.preview !== true) throw Object.assign(new Error('auth'), { code: P2P_ERR.AUTH })
              preview.collector.push(frame.bytes)
            } catch (error) { dropPreview(frame.id); fail(frame.id, error.code || P2P_ERR.BAD_REQUEST) }
            return
          }
          const up = frame && peer.uploads.get(frame.id)
          if (!up || up.ending) return
          if (up.ticket.exp <= Date.now()) { discardUpload(peer, up); return fail(up.id, P2P_ERR.AUTH) }
          if (!fileEnabled) { discardUpload(peer, up); return fail(up.id, P2P_ERR.FORBIDDEN) }
          up.lastActive = Date.now()
          up.got += frame.bytes.byteLength
          if (up.got > up.size) { discardUpload(peer, up); return fail(up.id, P2P_ERR.TOO_LARGE) }
          up.hash.update(frame.bytes)
          if (up.stream) { up.stream.write(Buffer.from(frame.bytes)); return }
          up.queued.push(Buffer.from(frame.bytes))
          up.queuedBytes += frame.bytes.byteLength
          if (up.queuedBytes > P2P_PUT_QUEUE_MAX) { discardUpload(peer, up); return fail(up.id, P2P_ERR.IO) }
          return
        }
        let msg
        try { msg = JSON.parse(data) } catch { return }
        if (!msg || typeof msg !== 'object') return
        if (msg.t === 'hello') {
          const payload = deps.verifyTicket(msg.ticket)
          if (!payload || payload.use !== 'p2p' || payload.mid !== deps.machineId || payload.sid !== sid) {
            fail(undefined, P2P_ERR.AUTH); setTimeout(() => closePeer(sid, 'bad ticket'), 200); return
          }
          tickets.set(String(payload.task), payload)
          while (tickets.size > 32) tickets.delete(tickets.keys().next().value)
          clearTimeout(helloTimer)
          send.json({ t: 'hello_ok', v: P2P_PROTOCOL_VERSION, daemon: deps.daemonVersion, chunk: P2P_CHUNK_SIZE, task: payload.task, inflight: P2P_RUNNER_MAX_INFLIGHT })
          return
        }
        if (!tickets.size) return fail(msg.id, P2P_ERR.AUTH)
        if (msg.t === 'ping') return send.json({ t: 'pong', n: msg.n })
        markTransfer()
        if (msg.t === 'cancel') {
          const up = peer.uploads.get(msg.id)
          if (previews.has(msg.id)) dropPreview(msg.id)
          if (up) discardUpload(peer, up)
          else if (activeGets.has(msg.id)) cancelled.add(msg.id)
          return
        }
        if (msg.t === 'preview_end') return await endPreview(msg)
        if (msg.t === 'put_end') return await endPut(msg)
        if (!Number.isSafeInteger(msg.id) || msg.id <= 0 || msg.id > 0xffffffff) return fail(undefined, P2P_ERR.BAD_REQUEST)
        const ticket = ticketFor(msg)
        if (!ticket) return fail(msg.id, P2P_ERR.AUTH)
        if (previews.has(msg.id) || peer.uploads.has(msg.id) || activeGets.has(msg.id)) return fail(msg.id, P2P_ERR.BUSY)
        if (msg.t === 'preview') return startPreview(msg, ticket)
        if (msg.t === 'put') { if (peer.uploads.size >= P2P_MAX_INFLIGHT) return fail(msg.id, P2P_ERR.BUSY); return doPut(msg, ticket) }
        if (msg.t === 'stat') {
          if (!fileEnabled || !ticket.down) return fail(msg.id, P2P_ERR.FORBIDDEN)
          const r = await resolveReadable(ticket, msg.path)
          if (!r.real) return fail(msg.id, r.code)
          let preview
          try { preview = await readArtifactPreview(r.real, r.st, msg.view) } catch { return fail(msg.id, P2P_ERR.NOT_FOUND) }
          preview ||= await displayImage(r.real, r.st, msg.view)
          return send.json({ t: 'stat_ok', id: msg.id, size: preview ? preview.bytes.length : r.st.size, mtime_ms: Math.round(r.st.mtimeMs), mime: preview?.mime || deps.mimeFor(r.real) })
        }
        if (msg.t === 'get') {
          if (inflight >= P2P_RUNNER_MAX_INFLIGHT) return fail(msg.id, P2P_ERR.BUSY)
          inflight++; activeGets.add(msg.id)
          try { await doGet(msg, ticket) } finally { inflight--; activeGets.delete(msg.id); cancelled.delete(msg.id) }
        }
      } catch (e) {
        log(`peer ${sid} handler error: ${e instanceof Error ? e.message : e}`)
      }
    })
  }

  // ---- WSS relay (default link) ------------------------------------------------------------
  // The Runner connects outbound to the relay machine (like its connection to the server, this works behind NAT
  // and needs no hole punching). Every browser session is multiplexed over this one connection, and the frames in a
  // session are identical to the frames on a peer-to-peer data channel, so the same attachChannel handles them and
  // authorization and read/write boundaries are unchanged.
  // Envelope: [1 byte type][1 byte sid length][sid][payload]; types: 0 text, 1 binary, 2 open session, 3
  // close session, 4 pause, 5 resume.
  const P2P_RELAY_TYPE = { TEXT: 0, BINARY: 1, OPEN: 2, CLOSE: 3, PAUSE: 4, RESUME: 5 }
  const p2pRelayText = new TextEncoder()
  const p2pRelayDecoder = new TextDecoder()
  let relayCfg = null // { url, ticket }: the latest values come from the heartbeat, and reconnects use the latest ticket
  let relaySocket = null
  let relayReady = false
  let relayTimer = null
  let relayWatch = null
  let relayBackoff = 1000
  let relayLastRx = 0
  const relayPipes = new Map() // sid -> pipe (looks like a node-datachannel DataChannel)

  const relayEnvelope = (type, sid, payload) => {
    const sidBytes = p2pRelayText.encode(sid)
    const body = payload === undefined ? new Uint8Array(0) : (typeof payload === 'string' ? p2pRelayText.encode(payload) : payload)
    const out = new Uint8Array(2 + sidBytes.length + body.length)
    out[0] = type; out[1] = sidBytes.length
    out.set(sidBytes, 2); out.set(body, 2 + sidBytes.length)
    return out
  }
  const relaySend = (type, sid, payload) => {
    if (!relayReady || !relaySocket || relaySocket.readyState !== 1) return false
    try { relaySocket.send(relayEnvelope(type, sid, payload)); return true } catch { return false }
  }

  function makeRelayPipe(sid) {
    let open = true
    let paused = false
    let lowTimer = null
    const handlers = { message: null, closed: null, low: null }
    const wake = () => { try { handlers.low?.() } catch { /* handled by the sender itself */ } }
    const pipe = {
      setBufferedAmountLowThreshold() {},
      onBufferedAmountLow(cb) { handlers.low = cb },
      sendMessage(text) { if (open) relaySend(P2P_RELAY_TYPE.TEXT, sid, text) },
      sendMessageBinary(bytes) { if (open) relaySend(P2P_RELAY_TYPE.BINARY, sid, bytes) },
      isOpen: () => open && relayReady && relaySocket?.readyState === 1,
      bufferedAmount() {
        // The browser on the relay side is slow (paused) or this outbound connection is backed up: either way it counts as
        // "buffer high" for makeSender, which waits for onBufferedAmountLow.
        const buffered = paused ? P2P_HIGH_WATER + 1 : (relaySocket?.bufferedAmount || 0)
        if (buffered > P2P_HIGH_WATER && !lowTimer) {
          lowTimer = setInterval(() => {
            if (!open || paused) { if (!open) { clearInterval(lowTimer); lowTimer = null } return }
            if ((relaySocket?.bufferedAmount || 0) <= P2P_LOW_WATER) { clearInterval(lowTimer); lowTimer = null; wake() }
          }, 20)
          lowTimer.unref?.()
        }
        return buffered
      },
      onOpen(cb) { cb() }, // the session was opened by the other side, so it is already connected by now
      onClosed(cb) { handlers.closed = cb },
      onMessage(cb) { handlers.message = cb },
      close() {
        if (!open) return
        open = false
        if (lowTimer) { clearInterval(lowTimer); lowTimer = null }
        relayPipes.delete(sid)
        relaySend(P2P_RELAY_TYPE.CLOSE, sid)
      },
      // Everything below is driven by the relay side
      deliver(data) { if (open) handlers.message?.(data) },
      setPaused(value) { paused = value; if (!value) wake() },
      remoteClosed() {
        if (!open) return
        open = false
        if (lowTimer) { clearInterval(lowTimer); lowTimer = null }
        relayPipes.delete(sid)
        handlers.closed?.()
      },
    }
    return pipe
  }

  function relayOpenSession(sid) {
    if (!/^[0-9a-f]{18}$/.test(sid) || !enabled) return
    if (peers.has(sid)) closePeer(sid, 'replaced')
    while (peers.size >= maxPeers) {
      const oldest = [...peers.entries()].sort((a, b) => a[1].lastActive - b[1].lastActive)[0]
      closePeer(oldest[0], 'evicted')
    }
    const pipe = makeRelayPipe(sid)
    relayPipes.set(sid, pipe)
    const peer = { pc: null, dc: null, state: 'open', openedAt: Date.now(), lastActive: Date.now(), uploads: new Map(), via: 'relay' }
    peers.set(sid, peer)
    startJanitor()
    attachChannel(sid, peer, pipe)
    log(`relay session ${sid} opened`)
  }

  function relayDisconnected(why) {
    if (relayWatch) { clearInterval(relayWatch); relayWatch = null }
    relayReady = false
    relaySocket = null
    for (const [sid, pipe] of [...relayPipes]) { pipe.remoteClosed(); closePeer(sid, `relay ${why}`) }
    relayPipes.clear()
    if (!relayCfg || !enabled) return
    clearTimeout(relayTimer)
    relayTimer = setTimeout(() => { relayTimer = null; relayConnect() }, relayBackoff)
    relayTimer.unref?.()
    relayBackoff = Math.min(relayBackoff * 2, 30_000)
  }

  function relayConnect() {
    if (relaySocket || !relayCfg || !enabled || typeof WebSocket !== 'function') return
    let ws
    try { ws = new WebSocket(`${relayCfg.url.replace(/\/+$/, '')}/runner`) } catch (error) { log(`relay connect failed: ${error.message}`); return relayDisconnected('connect error') }
    ws.binaryType = 'arraybuffer'
    relaySocket = ws
    relayLastRx = Date.now()
    ws.onopen = () => { try { ws.send(JSON.stringify({ t: 'runner_hello', ticket: relayCfg?.ticket || '' })) } catch { /* onclose will reconnect */ } }
    ws.onmessage = (event) => {
      relayLastRx = Date.now()
      const data = event.data
      if (typeof data === 'string') {
        let msg
        try { msg = JSON.parse(data) } catch { return }
        if (msg?.t === 'runner_ok') { relayReady = true; relayBackoff = 1000; log('relay connected') }
        else if (msg?.t === 'err') log(`relay refused: ${msg.code}`)
        return
      }
      const u8 = new Uint8Array(data)
      if (u8.length < 2 || u8[1] < 1 || u8.length < 2 + u8[1]) return
      const type = u8[0]
      const sid = p2pRelayDecoder.decode(u8.subarray(2, 2 + u8[1]))
      const payload = u8.subarray(2 + u8[1])
      if (type === P2P_RELAY_TYPE.OPEN) return relayOpenSession(sid)
      const pipe = relayPipes.get(sid)
      if (!pipe) return
      if (type === P2P_RELAY_TYPE.TEXT) pipe.deliver(p2pRelayDecoder.decode(payload))
      else if (type === P2P_RELAY_TYPE.BINARY) pipe.deliver(payload)
      else if (type === P2P_RELAY_TYPE.CLOSE) { pipe.remoteClosed(); closePeer(sid, 'relay closed') }
      else if (type === P2P_RELAY_TYPE.PAUSE) pipe.setPaused(true)
      else if (type === P2P_RELAY_TYPE.RESUME) pipe.setPaused(false)
    }
    ws.onclose = () => { if (relaySocket === ws) relayDisconnected('closed') }
    ws.onerror = () => { /* onclose fires afterwards */ }
    // The relay sends a text frame every 20 seconds. If nothing is received for 60 seconds, the outbound connection is
    // half dead, so disconnect and reconnect.
    relayWatch = setInterval(() => {
      if (Date.now() - relayLastRx > 60_000) { try { ws.close() } catch { /* */ } if (relaySocket === ws) relayDisconnected('stalled') }
    }, 10_000)
    relayWatch.unref?.()
  }

  function relayConfigure(cfg) {
    const next = cfg && typeof cfg.url === 'string' && /^wss?:\/\//.test(cfg.url) && typeof cfg.ticket === 'string' ? { url: cfg.url, ticket: cfg.ticket } : null
    if (!next || typeof WebSocket !== 'function' || !enabled) {
      relayCfg = null
      clearTimeout(relayTimer); relayTimer = null
      if (relaySocket) { const ws = relaySocket; relayDisconnected('disabled'); try { ws.close() } catch { /* */ } }
      return
    }
    const changedUrl = relayCfg?.url !== next.url
    relayCfg = next
    if (changedUrl && relaySocket) { const ws = relaySocket; relayDisconnected('url changed'); try { ws.close() } catch { /* */ } }
    if (!relaySocket && !relayTimer) relayConnect()
  }

  return {
    /** The p2p configuration from the heartbeat response. */
    configure(cfg) {
      // Peer-to-peer needs the native library; the WSS relay only needs WebSocket, so platforms without the
      // native library can still use the relay.
      const relayPossible = typeof WebSocket === 'function' && process.env.OPENTANDEM_P2P !== '0' && !!cfg?.relay_ws
      enabled = !!cfg?.enabled && (p2pSupportedHere() || relayPossible)
      // Older servers omitted file_enabled and used enabled for the file master switch.
      fileEnabled = enabled && cfg?.file_enabled !== false
      if (!fileEnabled) {
        for (const peer of peers.values()) {
          for (const up of peer.uploads.values()) {
            discardUpload(peer, up)
            try { peer.dc?.sendMessage(JSON.stringify({ t: 'err', id: up.id, code: P2P_ERR.FORBIDDEN })) } catch { /* already closed */ }
          }
          peer.uploads.clear()
        }
      }
      maxPeers = Number.isInteger(cfg?.max_peers) ? Math.max(1, Math.min(16, cfg.max_peers)) : 4
      // When the master switch is on, prepare the native library ahead of time so the first connection
      // request does not hit the download and time out.
      if (enabled && p2pSupportedHere()) p2pEnsureNative(log).catch(e => log(`native prepare failed: ${e.message}`))
      relayConfigure(cfg?.relay_ws)
      if (!enabled) {
        for (const sid of [...peers.keys()]) closePeer(sid, 'disabled')
        webPreview?.close(); webPreview = null
      }
    },
    isEnabled: () => enabled,
    /**
     * This Runner has just reported artifacts for a task: drop that task's cache so the next read checks
     * with the server again.
     */
    forgetTaskArtifacts(taskId) { serverAllow.delete(String(taskId || '')) },
    /**
     * Handle an offer forwarded by the server and return the answer sdp. Errors are thrown, and the caller
     * turns them into a command failure.
     */
    async handleOffer(offer) {
      if (!enabled) throw new Error('p2p disabled')
      const startedAt = Date.now()
      const sid = String(offer.session_id || '')
      if (!/^[0-9a-f]{18}$/.test(sid)) throw new Error('bad session id')
      if (peers.has(sid)) closePeer(sid, 'replaced')
      while (peers.size >= Math.min(maxPeers, Number(offer.max_peers) || maxPeers)) {
        const oldest = [...peers.entries()].sort((a, b) => a[1].lastActive - b[1].lastActive)[0]
        closePeer(oldest[0], 'evicted')
      }
      const native = await p2pEnsureNative(log)
      const iceServers = (Array.isArray(offer.ice_servers) ? offer.ice_servers : []).flatMap(server => {
        const urls = Array.isArray(server.urls) ? server.urls : [server.urls]
        return urls.filter(u => typeof u === 'string').map(url => {
          if (server.username && server.credential && /^turns?:/.test(url)) {
            const [scheme, rest] = [url.slice(0, url.indexOf(':')), url.slice(url.indexOf(':') + 1)]
            // TURN diagnostic usernames contain colons; both userinfo fields must be escaped.
            return `${scheme}:${encodeURIComponent(server.username)}:${encodeURIComponent(server.credential)}@${rest}`
          }
          return url
        })
      })
      const bind = process.env.OPENTANDEM_P2P_BIND?.trim()
      const pc = new native.PeerConnection(`ot-${sid}`, { iceServers, ...(bind ? { bindAddress: bind } : {}) })
      const peer = { pc, dc: null, state: 'new', openedAt: Date.now(), lastActive: Date.now(), uploads: new Map() }
      peers.set(sid, peer)
      startJanitor()
      pc.onStateChange(state => {
        log(`peer ${sid} state ${state}`)
        if (state === 'failed' || state === 'closed' || state === 'disconnected') closePeer(sid, state)
      })
      pc.onDataChannel(dc => {
        if (dc.getLabel() !== P2P_CHANNEL_LABEL) { try { dc.close() } catch { /* */ } return }
        attachChannel(sid, peer, dc)
      })
      let resolveNow = () => {}
      let stopTimer = () => {}
      const answered = new Promise((resolve, reject) => {
        const timer = setTimeout(() => reject(new Error('ice gathering timeout')), 6_000)
        stopTimer = () => clearTimeout(timer)
        resolveNow = () => {
          clearTimeout(timer)
          const d = pc.localDescription()
          resolve(d?.sdp || '')
        }
        pc.onGatheringStateChange(state => { if (state === 'complete') resolveNow() })
      })
      // If any step below throws first, nobody is waiting on this Promise anymore. Without this empty handler, the rejection
      // 6 seconds later becomes an unhandled Promise rejection that takes down the whole Runner process (one
      // bad offer can do that).
      answered.catch(() => {})
      try {
        pc.setRemoteDescription(String(offer.sdp), 'offer')
        // Candidate gathering may finish before the callback is registered (it completes synchronously when
        // there is no STUN),
        // so check the state once more.
        setTimeout(() => { if (pc.gatheringState() === 'complete') resolveNow() }, 0)
        const sdp = await answered
        if (!sdp) throw new Error('empty answer')
        log(`peer ${sid} answered in ${Date.now() - startedAt}ms`)
        return { sdp }
      } catch (error) {
        stopTimer()
        closePeer(sid, 'answer failed')
        throw error
      }
    },
    /** Whether a file request or chunk moved on any channel within the last ms milliseconds;
     *  self-update waits for this to clear. Keepalive pings do not count. */
    transferBusy(ms) { return Date.now() - lastTransferAt < ms },
    close() { for (const sid of [...peers.keys()]) closePeer(sid, 'shutdown'); webPreview?.close(); webPreview = null },
    peerCount: () => peers.size,
  }
}
