// Runner-side peer-to-peer file transfer: the browser reads and writes files on this computer directly
// over a WebRTC data channel, without going through OSS.
//
//   server (signaling)                     browser
//      | p2p_offer command                   |
//      v                                     |
//   handleOffer -- answer --> server --> browser
//   (data channel `ot-file`: see file-transport/protocol.mjs for the protocol)
//      ^                                     |
//      +------- direct UDP, or via the Tencent Cloud Guangzhou relay -------+
//
// Security boundary (if any one check fails, only an error frame is returned and the disk is not
// touched):
//   1. Without a session ticket signed by the server (hello), nothing is done; the ticket is bound to
//     this machine id, the session id, the task, read/write permission, and the expiry time.
//   2. Read: only allowed (1) the task's working directory (2) .sophon/uploads under the working
//     directory
//      (3) products this Runner itself has reported for this task (including static resources in the
//        same directory as an HTML file). The real path must still be inside these after resolution
//        (to guard against symlinks),
//      and credential-type files are always refused.
//   3. Write: only into <working directory from the ticket>/.sophon/uploads/<task id>/, the file name
//     is generated by the Runner, and it is renamed into place only after the size and sha256 are
//     verified.
//      There is no cap on the directory's total size or file count; flat files left from before the
//        per-task directories are kept as they are and remain readable.
//
// This file is bundled into the single-file Runner (runner/build/bundle.mjs): imports go only at the
// top of the file and may only reference relative-path modules or node: built-ins; exports use only
// export function / export const. Each module has its own scope, so top-level names no longer collide with machine-daemon.
